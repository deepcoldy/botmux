#!/usr/bin/env node
/**
 * Generate `src/adapters/cli/pi-initial-prompt-extension-data.ts` — the Pi
 * initial-prompt extension, embedded as a string constant so the text the
 * external `pi` process loads is byte-identical in EVERY runtime form botmux
 * ships in (tsx / node dist / compiled single-file binary).
 *
 * WHY THIS EXISTS: the extension text must be loadable by pi, which has no
 * transpiler. Deriving it from a live function via `.toString()` diverges per
 * runtime — MEASURED under tsx (`bun run daemon`, the no-build contributor
 * path): esbuild keepNames injects a module-scoped `__name` helper and the
 * serialized text references it as a free identifier, so pi dies with
 * `ReferenceError: __name is not defined` while registering the command. This
 * generator instead only ever reads the raw bytes of the pure-JS true source
 * (`pi-initial-prompt-extension.mjs`) and wraps them with JSON.stringify — no
 * transpiler touches the text, so injected helpers are structurally impossible.
 * Same shape as scripts/generate-app-icon-data.mjs; see its header for the
 * three-runtime-form measurements behind this pattern.
 *
 * GENERATED, NOT HAND-WRITTEN: the output is committed (so tsx/vitest work
 * with no build-step ordering), regenerated by `bun run build`, and
 * test/pi-initial-prompt.test.ts fails if the committed copy drifts from the
 * true source.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
/** 纯 JS 真源：扩展运行时体的唯一来源，生成器只读字节、不经任何转译器。 */
export const EXTENSION_SOURCE_PATH = join(REPO_ROOT, 'src', 'adapters', 'cli', 'pi-initial-prompt-extension.mjs');
export const EXTENSION_DATA_MODULE = join(REPO_ROOT, 'src', 'adapters', 'cli', 'pi-initial-prompt-extension-data.ts');

/** The exact text `EXTENSION_DATA_MODULE` must contain for the source at `sourcePath`. */
export function renderDataModule(sourcePath = EXTENSION_SOURCE_PATH) {
  const source = readFileSync(sourcePath, 'utf8');
  if (!source.includes('export default')) {
    throw new Error(`${sourcePath} has no default export — refusing to embed it`);
  }
  return [
    '// GENERATED by scripts/generate-pi-initial-prompt-extension.mjs — do not edit by hand.',
    '// Regenerate with `bun run build` (or `node scripts/generate-pi-initial-prompt-extension.mjs`).',
    '//',
    '// The Pi initial-prompt extension, embedded verbatim from its pure-JS true source',
    '// (src/adapters/cli/pi-initial-prompt-extension.mjs) so the text pi loads is',
    '// byte-identical under tsx / node dist / the compiled single-file binary.',
    `export const PI_INITIAL_PROMPT_EXTENSION_SOURCE = ${JSON.stringify(source)};`,
    '',
  ].join('\n');
}

// Only write when run directly, so tests can import `renderDataModule` to compare
// against the committed file without rewriting it as a side effect.
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const next = renderDataModule();
  let current = '';
  try { current = readFileSync(EXTENSION_DATA_MODULE, 'utf8'); } catch { /* first run */ }
  if (current === next) {
    console.log('[pi-extension] src/adapters/cli/pi-initial-prompt-extension-data.ts already up to date');
  } else {
    writeFileSync(EXTENSION_DATA_MODULE, next);
    console.log('[pi-extension] wrote src/adapters/cli/pi-initial-prompt-extension-data.ts');
  }
}
