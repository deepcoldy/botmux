#!/usr/bin/env node
/**
 * Generate `src/setup/app-icon-data.ts` — the default Feishu app icon, inlined as
 * base64 so it is reachable from EVERY runtime form botmux ships in.
 *
 * WHY THIS EXISTS
 * `setup`'s app-creation step uploads a 512×512 PNG as the new Feishu app's icon.
 * It used to locate that file on disk:
 *
 *     const here = dirname(fileURLToPath(import.meta.url));
 *     [join(here,'..','dashboard-web','favicon.png'),
 *      join(here,'..','dashboard','web','favicon.png')].find(existsSync)
 *
 * In the compiled single-file binary `import.meta.url` is `/$bunfs/root/…`, so
 * `here` is the VIRTUAL `/$bunfs/root` and both candidates miss. MEASURED by
 * compiling that exact function with `bun build --compile`:
 *
 *     here          = /$bunfs/root
 *     resolved icon = undefined      → throws `找不到 botmux 默认应用图标`
 *
 * and it misses even when a real favicon.png sits next to the binary, because
 * `here` never points at the filesystem at all. Users hit this creating a bot from
 * an install.sh / npm / bun global install — the whole bot-creation flow blocked.
 * This is the same class as the Dashboard 404 (88e3d7f24) and the missing
 * lark-scopes.json (2ef5c3a58): a `__dirname`-derived path read at runtime.
 *
 * ── WHY BASE64 AND NOT `with { type: 'file' }` ──────────────────────────────────
 * The Dashboard embeds its assets with `import … with { type: 'file' }` and that IS
 * the idiomatic Bun answer — but it only works under Bun. MEASURED, all three
 * candidates, same asset:
 *
 *   static  `import icon from './favicon.png' with { type: 'file' }`
 *     compiled ✅ embedded (/$bunfs/root/favicon-<hash>.png, 146308 bytes)
 *     node     ❌ ERR_UNKNOWN_FILE_EXTENSION
 *     tsx      ❌ fails to load
 *   dynamic `await import('./favicon.png', { with: { type: 'file' } })` + try/catch
 *     compiled ✅ embedded
 *     tsx      ❌ esbuild `Transform failed` — it cannot even parse it
 *   base64 constant module (this file's output)
 *     tsx      ✅ 146308 bytes, PNG magic 89504e47
 *     compiled ✅ 146308 bytes (run from outside the build dir)
 *     node     ✅ 146308 bytes (from tsc output)
 *
 * The Dashboard gets away with the Bun-only form because its preamble is INJECTED
 * at compile time (scripts/bun-native-embed-plugin.mjs prepends it to
 * `dist/dashboard.js`), so Node never parses it. `setup` is plain source compiled
 * by `tsc` and also run under tsx/vitest, so it needs a form all three accept.
 * A base64 constant is that form: an ordinary ESM string export, traced statically
 * into the binary and equally valid JavaScript everywhere.
 *
 * ── WHY THE DASHBOARD'S EXISTING EMBED DOES NOT ALREADY COVER THIS ─────────────
 * `dist/dashboard-web/favicon.png` IS embedded — but only into `dist/dashboard.js`,
 * and only reachable through `globalThis.__BOTMUX_DASHBOARD_ASSETS__`, which that
 * module populates. `setup` runs from the CLI without ever importing the dashboard
 * entry, so the map is absent there. Being embedded "somewhere in the binary" is not
 * the same as being reachable from the code that needs it.
 *
 * ── GENERATED, NOT HAND-WRITTEN ────────────────────────────────────────────────
 * Committed (so `tsc`, tsx and vitest all just work with no build step ordering),
 * but regenerated by `bun run build`, and `test/setup-app-icon.test.ts` fails if the
 * committed copy drifts from the PNG — otherwise editing the icon would silently
 * keep shipping the old bytes.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
/** Source of truth. `scripts/build-dashboard.mjs` copies this same file into dist. */
export const ICON_SOURCE = join(REPO_ROOT, 'src', 'dashboard', 'web', 'favicon.png');
export const ICON_MODULE = join(REPO_ROOT, 'src', 'setup', 'app-icon-data.ts');

/** The exact text `ICON_MODULE` must contain for the PNG at `iconPath`. */
export function renderIconModule(iconPath = ICON_SOURCE) {
  const png = readFileSync(iconPath);
  // Fail loudly rather than embedding whatever bytes happen to be there: a
  // truncated or replaced-by-text icon would upload fine and produce a broken app.
  if (png.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') {
    throw new Error(`${iconPath} is not a PNG (bad magic) — refusing to embed it`);
  }
  return [
    '// GENERATED by scripts/generate-app-icon-data.mjs — do not edit by hand.',
    '// Regenerate with `bun run build` (or `node scripts/generate-app-icon-data.mjs`).',
    '//',
    '// The default Feishu app icon, base64-inlined so `setup` can read it in every',
    '// runtime form: tsx/vitest, `node dist/`, AND the compiled single-file binary',
    '// (where a __dirname-derived path resolves to the virtual /$bunfs/root and any',
    '// on-disk lookup misses). See the generator for the measurements behind this.',
    `export const BOTMUX_APP_ICON_BASE64 = '${png.toString('base64')}';`,
    '',
    '/** Byte length of the decoded icon, so a caller can sanity-check the decode. */',
    `export const BOTMUX_APP_ICON_BYTES = ${png.length};`,
    '',
  ].join('\n');
}

// Only write when run directly, so tests can import `renderIconModule` to compare
// against the committed file without rewriting it as a side effect.
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const next = renderIconModule();
  let current = '';
  try { current = readFileSync(ICON_MODULE, 'utf8'); } catch { /* first run */ }
  if (current === next) {
    console.log('[app-icon] src/setup/app-icon-data.ts already up to date');
  } else {
    writeFileSync(ICON_MODULE, next);
    console.log(`[app-icon] wrote src/setup/app-icon-data.ts (${readFileSync(ICON_SOURCE).length} bytes of PNG)`);
  }
}
