#!/usr/bin/env node
/**
 * Generate `src/adapters/cli/pi-turn-boundary-extension-data.ts` — the Pi
 * turn-boundary & system-prompt extension, embedded as a string constant so the
 * text the external `pi` process loads is byte-identical in EVERY runtime form
 * botmux ships in (tsx / node dist / compiled single-file binary).
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const EXTENSION_SOURCE_PATH = join(REPO_ROOT, 'src', 'adapters', 'cli', 'pi-turn-boundary-extension.mjs');
export const EXTENSION_DATA_MODULE = join(REPO_ROOT, 'src', 'adapters', 'cli', 'pi-turn-boundary-extension-data.ts');

export function renderDataModule(sourcePath = EXTENSION_SOURCE_PATH) {
  const source = readFileSync(sourcePath, 'utf8');
  if (!source.includes('export default')) {
    throw new Error(`${sourcePath} has no default export — refusing to embed it`);
  }
  return [
    '// GENERATED by scripts/generate-pi-turn-boundary-extension.mjs — do not edit by hand.',
    '// Regenerate with `bun run build` (or `node scripts/generate-pi-turn-boundary-extension.mjs`).',
    '//',
    '// The Pi turn-boundary extension, embedded verbatim from its pure-JS true source',
    '// (src/adapters/cli/pi-turn-boundary-extension.mjs) so the text pi loads is',
    '// byte-identical under tsx / node dist / the compiled single-file binary.',
    `export const PI_TURN_BOUNDARY_EXTENSION_SOURCE = ${JSON.stringify(source)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const next = renderDataModule();
  let current = '';
  try { current = readFileSync(EXTENSION_DATA_MODULE, 'utf8'); } catch { /* first run */ }
  if (current === next) {
    console.log('[pi-turn-boundary-extension] src/adapters/cli/pi-turn-boundary-extension-data.ts already up to date');
  } else {
    writeFileSync(EXTENSION_DATA_MODULE, next);
    console.log('[pi-turn-boundary-extension] wrote src/adapters/cli/pi-turn-boundary-extension-data.ts');
  }
}
