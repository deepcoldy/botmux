#!/usr/bin/env node
/**
 * Generate `src/services/zcode-provider-helper-data.ts` — the ZCode provider
 * bridge, embedded as a string constant.
 *
 * WHY THIS EXISTS: the bridge started life as `scripts/zcode-provider-helper.mjs`
 * and was invoked from `~/.botmux/bin/zcode-provider-helper.mjs`, but nothing
 * ever wrote it there. `tsc` does not copy `.mjs` into `dist`, the npm `files`
 * whitelist does not include it, and the compiled single-file binary only embeds
 * modules that something imports. On an ordinary install the file therefore
 * never existed, and `prepareZcodeSessionModel` — which runs for every non-reattach
 * ZCode launch and is fail-closed — aborted the launch of every ZCode topic.
 *
 * Same shape as scripts/generate-pi-initial-prompt-extension.mjs: read the pure
 * .mjs bytes and JSON.stringify them, so no transpiler can inject helpers into
 * the text the external bun process loads. The output is committed (tsx/vitest
 * work with no build-step ordering) and regenerated by `bun run build`.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const HELPER_SOURCE_PATH = join(REPO_ROOT, 'scripts', 'zcode-provider-helper.mjs');
export const HELPER_DATA_MODULE = join(REPO_ROOT, 'src', 'services', 'zcode-provider-helper-data.ts');

/** The exact text `HELPER_DATA_MODULE` must contain for the source at `sourcePath`. */
export function renderDataModule(sourcePath = HELPER_SOURCE_PATH) {
  const source = readFileSync(sourcePath, 'utf8');
  if (!source.includes('ZCODE_PERSONAL_PROVIDER_CONFIG_FILE')) {
    throw new Error(`${sourcePath} is not the ZCode provider bridge — refusing to embed it`);
  }
  return [
    '// GENERATED by scripts/generate-zcode-provider-helper-data.mjs — do not edit by hand.',
    '// Regenerate with `bun run build` (or `node scripts/generate-zcode-provider-helper-data.mjs`).',
    '//',
    '// The ZCode provider bridge, embedded verbatim from its pure-JS true source',
    '// (scripts/zcode-provider-helper.mjs) so it can be written to ~/.botmux/bin at',
    '// runtime. See the generator header for why a shipped .mjs path never worked.',
    '',
    `export const ZCODE_PROVIDER_HELPER_SOURCE = ${JSON.stringify(source)};`,
    '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(HELPER_DATA_MODULE, renderDataModule(), 'utf8');
  console.log(`wrote ${HELPER_DATA_MODULE}`);
}
