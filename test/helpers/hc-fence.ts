import * as nodeFs from 'node:fs';
import * as nodeChildProcess from 'node:child_process';
import { basename, delimiter, isAbsolute, join } from 'node:path';

// Captured when this module is first evaluated, from the runners' setup /
// preload, before any test module can mock node:fs or node:child_process.
const {
  chmodSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync,
} = { ...nodeFs };
const { spawnSync } = { ...nodeChildProcess };

/**
 * Test-wide hc (herdr-core) fence: no test may reach the HOST's hc cores.
 *
 * WHY: an hc client that cannot connect starts a core itself, and a core binds
 * by unlinking whatever sits at its socket path first. Without XDG_RUNTIME_DIR
 * hc falls back to /run/user/<uid>, so a test with a fenced HOME (another state
 * dir, another lock) takes over the live core's socket and, because that is
 * the default runtime dir, starts real `hc-serve-*` units via
 * `systemd-run --user`.
 *
 * Two layers, shared by vitest (setup files), `bun test` (preload) and
 * scripts/fenced-run.ts:
 *   1. env: every test process gets its own EXISTING, short XDG_RUNTIME_DIR
 *      (hc socket paths are capped at 107 bytes; a custom runtime dir also
 *      keeps hc off systemd), a unique HC_SESSION, a private XDG_STATE_HOME,
 *      and loses every inherited HC_* variable;
 *   2. `hc` / `herdr-core` shims first on PATH, and BOTMUX_HC_BIN naming one,
 *      that resolve the socket exactly like hc (HC_SOCKET, else `socket` in
 *      $XDG_CONFIG_HOME/herdr-core/config.toml, else
 *      $XDG_RUNTIME_DIR/herdr-core/$HC_SESSION.sock) and refuse, exit 1 plus a
 *      line in the deny log, a socket under /run/user/<uid>, an unset or host
 *      XDG_RUNTIME_DIR, or the host's own hc config. Otherwise they exec
 *      BOTMUX_HC_TEST_BIN: the caller's if set, else the run's, baked in at
 *      creation because hc's control env (hcControlEnv) drops every BOTMUX*
 *      key. Without one they exit 127, so code under test sees hc as not
 *      installed. A non-empty deny log fails the run.
 * XDG_CONFIG_HOME is only set when the caller names a fenced home: the e2e
 * project keeps the real HOME because real CLIs read their config there, and
 * the shim's host-config refusal covers hc instead.
 * Not covered: hc invoked by absolute path, or a child whose hand-built env
 * drops both PATH and XDG_RUNTIME_DIR.
 */

export interface HcFence {
  /** Short private root (hc socket paths are capped at 107 bytes). */
  root: string;
  /** Directory holding the `hc` / `herdr-core` shims, or null on Windows. */
  binDir: string | null;
  denyLog: string;
}

const FENCE_ROOT_PREFIX = '/tmp/bmhc-';
const SHIM_NAMES = ['hc', 'herdr-core'] as const;
const HC_ENV_KEY = /^_?HC_/;

function shellSingleQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/**
 * awk: print the top-level `socket` value of an hc config.toml (the single
 * quote comes in as `sq`); exit 2 when the key is there but is not a one-line
 * string the shim can read without a TOML parser.
 */
const CONFIG_SOCKET_AWK = String.raw`
/^[ \t\r]*\[/ { exit }
{
  line = $0
  sub(/^[ \t\r]+/, "", line)
  key = line
  sub(/[ \t]*=.*/, "", key)
  if (key != "socket" && key != "\"socket\"" && key != sq "socket" sq) next
  sub(/^[^=]*=[ \t]*/, "", line)
  q = substr(line, 1, 1)
  rest = substr(line, 2)
  stop = index(rest, q)
  if ((q != "\"" && q != sq) || stop < 2) { bad = 1; exit }
  value = substr(rest, 1, stop - 1)
  if (q == "\"" && index(value, "\\")) { bad = 1; exit }
  if (substr(rest, stop + 1) !~ /^[ \t\r]*(#.*)?$/) { bad = 1; exit }
  print value
  exit
}
END { exit bad ? 2 : 0 }
`;

/** The hc config files of the INVOKING environment. */
export function hostHcConfigFiles(env: NodeJS.ProcessEnv = process.env): string[] {
  const homes = [env.XDG_CONFIG_HOME, env.HOME ? join(env.HOME, '.config') : undefined];
  return [...new Set(homes.filter((home): home is string => !!home).map(home => join(home, 'herdr-core', 'config.toml')))];
}

/**
 * POSIX sh shim: resolve the socket like hc does, refuse the host's cores.
 * `runHc` is the run's BOTMUX_HC_TEST_BIN, used when the caller's env has none.
 */
export function hcFenceShimScript(
  denyLog: string,
  binDir: string,
  hostConfigs: readonly string[],
  runHc = '',
): string {
  return `#!/bin/sh
# Generated by test/helpers/hc-fence.ts — refuses the host's hc cores in tests.
set -f
DENY_LOG=${shellSingleQuote(denyLog)}
BIN_DIR=${shellSingleQuote(binDir)}
HOST_CONFIGS=${shellSingleQuote(hostConfigs.join('\n'))}
RUN_HC=${shellSingleQuote(runHc)}
ARGS=$*
host_run=/run/user/$(id -u)

deny() {
  printf '%s\\t%s\\t%s\\n' "$1" "$PWD" "$ARGS" >> "\${BOTMUX_HC_FENCE_LOG:-$DENY_LOG}"
  echo "botmux test hc fence: refusing $1 (args: $ARGS): $2" >&2
  exit 1
}

# Physical path, resolving the longest existing prefix (hc creates the rest);
# fails on a '..' in the part that does not exist yet.
canon() {
  p=$1
  case $p in /*) ;; *) p=$PWD/$p ;; esac
  rest=
  while [ ! -d "$p" ]; do
    rest=/\${p##*/}$rest
    p=\${p%/*}
    [ -n "$p" ] || p=/
  done
  case $rest/ in */../*) return 1 ;; esac
  dir=$(cd "$p" 2>/dev/null && pwd -P) || return 1
  printf '%s\\n' "\${dir%/}$rest"
}

host=$(canon "$host_run") || host=$host_run
under_host() {
  case $1 in "$host_run"|"$host_run"/*|"$host"|"$host"/*) return 0 ;; esac
  return 1
}

check() {
  c=$(canon "$1") || deny "hc socket $1 ($2)" 'the fence cannot resolve this path.'
  if under_host "$c"; then
    deny "hc socket $1 ($2)" "it lies in the host runtime dir $host_run, where the host's hc cores listen."
  fi
}

case \${1-} in
  --version|-V|--help|-h|help) ;;
  *)
    run=\${XDG_RUNTIME_DIR-}
    if [ -z "$run" ]; then
      deny 'an unset XDG_RUNTIME_DIR' "hc would fall back to $host_run, start its core through systemd-run --user and could take over the host core's socket. Give it a private XDG_RUNTIME_DIR that exists."
    fi
    c=$(canon "$run") || deny "XDG_RUNTIME_DIR=$run" 'the fence cannot resolve this path.'
    if under_host "$c"; then
      deny "XDG_RUNTIME_DIR=$run" "it is the host runtime dir $host_run."
    fi

    if [ -n "\${XDG_CONFIG_HOME-}" ]; then config=$XDG_CONFIG_HOME
    elif [ -z "\${HOME+set}" ]; then config=/.config
    elif [ -z "$HOME" ]; then config=.config
    else config=$HOME/.config
    fi
    config=$config/herdr-core/config.toml
    if [ -f "$config" ]; then
      cc=$(canon "$config") || cc=$config
      old_ifs=$IFS
      IFS='
'
      for host_config in $HOST_CONFIGS; do
        hcc=$(canon "$host_config") || hcc=$host_config
        if [ "$cc" = "$hcc" ]; then
          IFS=$old_ifs
          deny "hc config $config" "it is the host's own hc config, whose socket key would steer this hc. Point XDG_CONFIG_HOME at a private directory."
        fi
      done
      IFS=$old_ifs
    fi

    if [ -n "\${HC_SOCKET-}" ]; then
      check "$HC_SOCKET" HC_SOCKET
    else
      if [ -r "$config" ]; then
        sock=$(awk -v sq="'" '${CONFIG_SOCKET_AWK}' "$config") || deny "hc config $config" 'the fence cannot read its socket key; write it as a plain quoted string.'
        [ -z "$sock" ] || check "$sock" "socket in $config"
      fi
      session=$(printf '%s' "\${HC_SESSION-}" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
      [ -n "$session" ] || session=default
      check "$run/herdr-core/$session.sock" XDG_RUNTIME_DIR
    fi

    sub=
    for a in "$@"; do case $a in -*) ;; *) sub=$a; break ;; esac; done
    if [ "$sub" = hold ]; then
      expect=
      for a in "$@"; do
        if [ -n "$expect" ]; then check "$a" 'hold --socket'; expect=; continue; fi
        case $a in --socket) expect=1 ;; --socket=*) check "\${a#--socket=}" 'hold --socket' ;; esac
      done
    fi ;;
esac

REAL=\${BOTMUX_HC_TEST_BIN-$RUN_HC}
if [ -z "$REAL" ]; then
  echo 'botmux test hc fence: hc not available inside the test fence (set BOTMUX_HC_TEST_BIN to a real herdr-core binary to run hc tests).' >&2
  exit 127
fi
case $REAL in
  "$BIN_DIR"/*) echo "botmux test hc fence: BOTMUX_HC_TEST_BIN=$REAL is the fence's own shim." >&2; exit 127 ;;
  /*) ;;
  *) echo "botmux test hc fence: BOTMUX_HC_TEST_BIN must be an absolute path, got $REAL." >&2; exit 127 ;;
esac
exec "$REAL" "$@"
`;
}

/** Create the per-run fence (vitest globalSetup / bun preload / fenced-run)
 *  from the INVOKING environment: its hc config is recognised as the host's,
 *  and its BOTMUX_HC_TEST_BIN becomes the run's. */
export function createHcFence(env: NodeJS.ProcessEnv = process.env): HcFence {
  const root = mkdtempSync(FENCE_ROOT_PREFIX);
  const denyLog = join(root, 'denied.log');
  writeFileSync(denyLog, '');
  if (process.platform === 'win32') return { root, binDir: null, denyLog };
  const binDir = join(root, 'bin');
  mkdirSync(binDir);
  const script = hcFenceShimScript(denyLog, binDir, hostHcConfigFiles(env), env.BOTMUX_HC_TEST_BIN ?? '');
  for (const name of SHIM_NAMES) {
    writeFileSync(join(binDir, name), script);
    chmodSync(join(binDir, name), 0o755);
  }
  return { root, binDir, denyLog };
}

/**
 * Fence one test process. `home` is the fenced HOME when there is one; its
 * XDG dirs then hold hc's config and state.
 */
export function applyHcFenceEnv(
  fence: HcFence,
  env: NodeJS.ProcessEnv = process.env,
  opts: { home?: string } = {},
): { runtimeDir: string; denyLog: string } {
  const fileRoot = mkdtempSync(join(fence.root, 'f-'));
  const runtimeDir = join(fileRoot, 'run');
  mkdirSync(runtimeDir, { mode: 0o700 });
  const denyLog = join(fileRoot, 'denied.log');
  writeFileSync(denyLog, '');
  for (const key of Object.keys(env)) {
    if (HC_ENV_KEY.test(key)) delete env[key];
  }
  env.HC_SESSION = `bmt-${basename(fileRoot).slice('f-'.length)}`;
  env.XDG_RUNTIME_DIR = runtimeDir;
  env.XDG_STATE_HOME = opts.home ? join(opts.home, '.local', 'state') : join(fileRoot, 'state');
  if (opts.home) env.XDG_CONFIG_HOME = join(opts.home, '.config');
  env.BOTMUX_HC_FENCE_LOG = denyLog;
  if (fence.binDir) {
    env.BOTMUX_HC_BIN = join(fence.binDir, 'herdr-core');
    const parts = (env.PATH ?? '').split(delimiter).filter(part => part && part !== fence.binDir);
    env.PATH = [fence.binDir, ...parts].join(delimiter);
  } else {
    delete env.BOTMUX_HC_BIN;
  }
  return { runtimeDir, denyLog };
}

export function readHcFenceLog(path: string): string[] {
  try {
    return readFileSync(path, 'utf8').split('\n').filter(Boolean);
  } catch {
    return [];
  }
}

/** Every refusal of the run: the run log plus each process's own log. */
export function readHcFenceDenials(fence: Pick<HcFence, 'root' | 'denyLog'>): string[] {
  let fileRoots: string[] = [];
  try { fileRoots = readdirSync(fence.root).filter(name => name.startsWith('f-')); } catch { /* gone */ }
  return [fence.denyLog, ...fileRoots.map(name => join(fence.root, name, 'denied.log'))].flatMap(readHcFenceLog);
}

function stopPrivateCores(fileRoot: string, realHc: string, path: string | undefined): void {
  const runtimeDir = join(fileRoot, 'run');
  const socketDir = join(runtimeDir, 'herdr-core');
  let names: string[] = [];
  try { names = readdirSync(socketDir); } catch { return; }
  for (const name of names) {
    if (!name.endsWith('.sock') || name.includes('.holder.')) continue;
    // An explicit socket INSIDE the private root: can never address a host
    // core. `server stop` only connects; it never starts one.
    spawnSync(realHc, ['server', 'stop'], {
      stdio: 'ignore',
      timeout: 10_000,
      env: {
        PATH: path,
        HOME: fileRoot,
        XDG_RUNTIME_DIR: runtimeDir,
        XDG_STATE_HOME: join(fileRoot, 'state'),
        XDG_CONFIG_HOME: join(fileRoot, 'config'),
        HC_SESSION: name.slice(0, -'.sock'.length),
        HC_SOCKET: join(socketDir, name),
      },
    });
  }
}

/** Stop every private core the run left behind (which ends their terminals),
 *  then drop the root. */
export function teardownHcFence(fence: HcFence, env: NodeJS.ProcessEnv = process.env): void {
  const realHc = env.BOTMUX_HC_TEST_BIN;
  if (realHc && isAbsolute(realHc) && existsSync(fence.root)) {
    for (const name of readdirSync(fence.root)) {
      if (name.startsWith('f-')) stopPrivateCores(join(fence.root, name), realHc, env.PATH);
    }
  }
  rmSync(fence.root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
}

export function hcFenceDenialError(denials: readonly string[]): Error {
  return new Error(
    `hc test fence refused ${denials.length} attempt(s) to reach a HOST hc core ` +
    '(what\tcwd\targs):\n' + denials.join('\n'),
  );
}
