/**
 * The fleet supervisor must escape a bot session's cleanup scope: started from
 * inside a bot session it lived in that session's systemd scope, so the
 * session's own close / CLI restart (which stops its scope) would SIGKILL every
 * daemon and worker with it. Any OTHER unit the operator chose must keep it.
 */
import { describe, expect, it, vi } from 'vitest';
import { moveSupervisorIntoFleetScope, type FleetScopeRuntime } from '../src/core/fleet-scope.js';
import { probeSystemdPidNamespace, sessionScopeUnitName } from '../src/core/session-scope.js';
import { readProcessSystemdUnit } from '../src/utils/systemd-unit.js';

function runtime(unit: string, over: Partial<FleetScopeRuntime> = {}) {
  let current = unit;
  const run = vi.fn((_command: string, args: readonly string[]) => {
    current = args[7];  // StartTransientUnit's unit name argument
    return { status: 0, stderr: '' };
  });
  return {
    rt: {
      platform: 'linux' as const,
      pid: 4242,
      readUnit: () => current,
      busEnv: () => ({ XDG_RUNTIME_DIR: '/run/user/0', DBUS_SESSION_BUS_ADDRESS: 'unix:path=/run/user/0/bus' }),
      pidNamespace: () => ({ shared: true, basis: 'initial-namespace', namespace: 'pid:[4026531836]' }),
      run,
      now: () => 1_000_000,
      sleepMs: () => {},
      ...over,
    } satisfies Partial<FleetScopeRuntime>,
    run,
  };
}

describe('moveSupervisorIntoFleetScope', () => {
  it('moves only a supervisor started inside a botmux session scope', () => {
    // Generated by the producer: renaming the session-scope prefix must turn
    // THIS file red, not only session-scope's own tests.
    const unit = sessionScopeUnitName('fc17c9ee-fa8f-46f4-93cc-58c7ac288696');
    const { rt, run } = runtime(unit);
    const outcome = moveSupervisorIntoFleetScope(rt);
    expect(outcome).toMatchObject({ action: 'moved', from: unit });
    expect(outcome.action === 'moved' && outcome.to).toMatch(/^botmux-fleet-[a-z0-9]+-4242\.scope$/);
    const [command, args] = run.mock.calls[0];
    expect(command).toBe('busctl');
    expect(args.slice(0, 7)).toEqual(['--user', 'call', 'org.freedesktop.systemd1', '/org/freedesktop/systemd1',
      'org.freedesktop.systemd1.Manager', 'StartTransientUnit', 'ssa(sv)a(sa(sv))']);
    expect(args).toEqual(expect.arrayContaining(['PIDs', 'au', '1', '4242']));
  });

  it.each(['botmux.service', 'botmux-watchdog.service', 'botmux-fleet-k3x9-77.scope'])(
    'keeps a supervisor that already runs in the fleet unit %s', unit => {
      const { rt, run } = runtime(unit);
      expect(moveSupervisorIntoFleetScope(rt)).toEqual({ action: 'kept', unit });
      expect(run).not.toHaveBeenCalled();
    },
  );

  // An operator who runs botmux under their own unit must keep owning it:
  // leaving the unit would make their systemctl stop/restart lose the fleet.
  it.each([
    'session-12.scope', // logind login scope (manual `botmux start` over SSH)
    'my-botmux.service', // operator-managed service
    'my-own-botmux-123.scope', // operator-managed scope
    'cron.service',
    'app.slice',
    // Other botmux-prefixed units are NOT session cleanup scopes; only the
    // exact botmux-session-*.scope shape may be left (pins the regex prefix).
    'botmux-daemon-helper.scope',
    'botmux-plugin-x.scope',
  ])('never leaves a non-botmux unit (%s)', unit => {
    const { rt, run } = runtime(unit);
    expect(moveSupervisorIntoFleetScope(rt)).toEqual({ action: 'kept', unit });
    expect(run).not.toHaveBeenCalled();
  });

  it('starts where it is when the move is impossible or fails', () => {
    // No user bus while inside a session scope: cannot move, say so explicitly.
    const noBus = runtime('botmux-session-abc.scope', { busEnv: () => undefined });
    expect(moveSupervisorIntoFleetScope(noBus.rt).action).toBe('unsupported');
    expect(noBus.run).not.toHaveBeenCalled();

    // No user bus outside a session scope is irrelevant — nothing to move from.
    const noBusElsewhere = runtime('session-3.scope', { busEnv: () => undefined });
    expect(moveSupervisorIntoFleetScope(noBusElsewhere.rt)).toEqual({ action: 'kept', unit: 'session-3.scope' });

    const refused = runtime('botmux-session-abc.scope', { run: vi.fn(() => ({ status: 1, stderr: 'Access denied' })) });
    expect(moveSupervisorIntoFleetScope(refused.rt)).toMatchObject({ action: 'failed', unit: 'botmux-session-abc.scope', reason: 'Access denied' });

    const notMoved = runtime('botmux-session-abc.scope', { run: vi.fn(() => ({ status: 0, stderr: '' })) });
    expect(moveSupervisorIntoFleetScope(notMoved.rt)).toMatchObject({ action: 'failed', unit: 'botmux-session-abc.scope' });

    expect(moveSupervisorIntoFleetScope({ ...runtime('botmux-session-abc.scope').rt, platform: 'darwin' }).action).toBe('unsupported');
  });

  // StartTransientUnit's PIDs=[our pid] is resolved in user systemd's PID
  // namespace: from an isolated sandbox sharing the host's user bus it moves
  // whichever host process carries that number.
  describe('hands user systemd its PID only from the same PID namespace', () => {
    const unit = sessionScopeUnitName('fc17c9ee-fa8f-46f4-93cc-58c7ac288696');

    it('moves where user systemd shares the namespace', () => {
      const { rt, run } = runtime(unit, { pidNamespace: () => ({ shared: true, basis: 'user-bus', namespace: 'pid:[4026532999]' }) });
      expect(moveSupervisorIntoFleetScope(rt).action).toBe('moved');
      expect(run).toHaveBeenCalledTimes(1);
    });

    it.each([
      ['in another namespace', () => probeSystemdPidNamespace({
        platform: 'linux',
        readlink: path => (path === '/proc/self/ns/pid' ? 'pid:[4026532999]' : 'pid:[4026531836]'),
        readFile: () => 'NSpid:\t42\n',
        run: () => ({ status: 0, stdout: 'Unique=:1.42\n', stderr: '', error: undefined }),
      })],
      ['when the check failed', () => probeSystemdPidNamespace({
        platform: 'linux',
        readlink: () => { throw new Error('EACCES'); },
      })],
    ])('stays put %s and says why', (_label, pidNamespace) => {
      const { rt, run } = runtime(unit, { pidNamespace });
      expect(moveSupervisorIntoFleetScope(rt)).toEqual({ action: 'unsupported', reason: expect.any(String) });
      expect(run).not.toHaveBeenCalled();
    });
  });
});

describe('readProcessSystemdUnit', () => {
  it.runIf(process.platform === 'linux')('reads the unit leaf from cgroup v1 and v2 membership', () => {
    const v1 = '12:memory:/user.slice\n1:name=systemd:/user.slice/user-0.slice/user@0.service/app.slice/botmux-session-ab.scope\n0::/user.slice\n';
    expect(readProcessSystemdUnit(77, () => v1)).toBe('botmux-session-ab.scope');
    const v2 = '0::/user.slice/user-0.slice/session-4.scope\n';
    expect(readProcessSystemdUnit(77, () => v2)).toBe('session-4.scope');
    expect(readProcessSystemdUnit(77, () => { throw new Error('ENOENT'); })).toBeUndefined();
  });
});
